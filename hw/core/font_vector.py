"""
Встроенный однолинейный (штриховой) векторный шрифт.

Используется как:
  * шрифт по умолчанию, пока пользователь не оцифровал свой почерк;
  * подписи на шаблонном листе для сбора почерка;
  * запасной вариант для символов, которых нет в пользовательском шрифте.

Глифы заданы строками в стиле SVG-path (только абсолютные команды):
    M x y   — перенести перо (начать новый штрих)
    L x y   — линия
    H x     — горизонтальная линия
    V y     — вертикальная линия
    C x1 y1 x2 y2 x y — кубическая кривая Безье
    Q x1 y1 x y       — квадратичная кривая Безье
    Z       — замкнуть текущий штрих
    O cx cy r         — окружность (точки над i, ё, знаки препинания)

Метрики в условных единицах шрифта:
    базовая линия = 0, CAP = 14, x-height = 9,
    нижний выносной = -4, верхний предел с диакритикой (Й, Ё) = 18.
Параметр размера в мм задаёт высоту ЗАГЛАВНОЙ буквы: scale = size_mm / CAP.
"""

import math
import re
import unicodedata

CAP = 14.0        # высота заглавных
XH = 9.0          # высота строчных
DESC = -4.0       # нижний выносной элемент (у, р, д, ц, щ)
ASC = 18.0        # верхний предел с диакритикой (Й, Ў)

