# --------------------------------------------------------------- парсер путей

_TOKEN = re.compile(r"([MLHVCQZO])|(-?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?)")


def _tokens(d):
    for m in _TOKEN.finditer(d):
        yield m.group(1) if m.group(1) else float(m.group(2))


def _cubic(p0, p1, p2, p3, flat):
    """Тесселяция кубической кривой: чем длиннее, тем больше сегментов."""
    ln = math.dist(p0, p1) + math.dist(p1, p2) + math.dist(p2, p3)
    n = max(4, min(64, int(ln / max(flat, 1e-6)) + 1))
    pts = []
    for i in range(1, n + 1):
        t = i / n
        u = 1.0 - t
        a, b, c, e = u * u * u, 3 * u * u * t, 3 * u * t * t, t * t * t
        pts.append((a * p0[0] + b * p1[0] + c * p2[0] + e * p3[0],
                    a * p0[1] + b * p1[1] + c * p2[1] + e * p3[1]))
    return pts


def _circle(cx, cy, r, flat):
    n = max(8, min(72, int(2 * math.pi * r / max(flat, 1e-6)) + 1))
    return [(cx + r * math.cos(2 * math.pi * i / n),
             cy + r * math.sin(2 * math.pi * i / n)) for i in range(n + 1)]


def parse_path(d, flat=0.35):
    """Строка пути -> список полилиний [[(x, y), ...], ...]."""
    polys, cur = [], []
    x = y = sx = sy = 0.0
    it = list(_tokens(d))
    i, n = 0, len(it)
    cmd = None

    def flush():
        nonlocal cur
        if len(cur) > 1:
            polys.append(cur)
        cur = []

    while i < n:
        t = it[i]
        if isinstance(t, str):
            cmd = t
            i += 1
            if cmd == "Z":
                if cur:
                    cur.append((sx, sy))
                    x, y = sx, sy
                cmd = "L"
                continue
        if cmd is None:
            raise ValueError("путь начинается не с команды: %r" % d[:40])

        if cmd == "M":
            flush()
            x, y = it[i], it[i + 1]
            i += 2
            sx, sy = x, y
            cur = [(x, y)]
            cmd = "L"                       # повторные пары после M — линии
        elif cmd == "L":
            x, y = it[i], it[i + 1]
            i += 2
            cur.append((x, y))
        elif cmd == "H":
            x = it[i]
            i += 1
            cur.append((x, y))
        elif cmd == "V":
            y = it[i]
            i += 1
            cur.append((x, y))
        elif cmd == "C":
            p1 = (it[i], it[i + 1])
            p2 = (it[i + 2], it[i + 3])
            p3 = (it[i + 4], it[i + 5])
            i += 6
            cur.extend(_cubic((x, y), p1, p2, p3, flat))
            x, y = p3
        elif cmd == "Q":
            qx, qy = it[i], it[i + 1]
            px, py = it[i + 2], it[i + 3]
            i += 4
            p1 = (x + 2.0 / 3 * (qx - x), y + 2.0 / 3 * (qy - y))
            p2 = (px + 2.0 / 3 * (qx - px), py + 2.0 / 3 * (qy - py))
            cur.extend(_cubic((x, y), p1, p2, (px, py), flat))
            x, y = px, py
        elif cmd == "O":
            flush()
            cx, cy, r = it[i], it[i + 1], it[i + 2]
            i += 3
            polys.append(_circle(cx, cy, r, flat))
        else:
            raise ValueError("неизвестная команда %r" % cmd)
    flush()
    return polys


